export function stepText(s, lang2) {
  const i = Math.max(
    0,
    languages.findIndex((l) => l[0] === lang2)
  ), p = s.params;
  let text = moves[s.kind]?.[i] || (s.kind.startsWith("root") || s.kind === "roundRoot" ? tr("roots", lang2) : s.kind === "commonParts" || s.kind === "combineParts" ? skillName("fractions", lang2) : tr("step", lang2));
  let math = "";
  switch (s.kind) {
    case "remainder":
      math = `${p.a} = ${p.divisor} \xD7 ${p.quotient} + ${p.remainder}; ${p.quotient} + ${p.remainder}/${p.divisor} = ${p.result}`;
      break;
    case "signRule":
      math = `${p.a} ${p.op} (${p.b}) = ${p.result}`;
      break;
    case "fractionProduct":
      math = `(${p.left} \xD7 ${p.right}) / (${p.leftDen} \xD7 ${p.rightDen}) = ${p.result}`;
      break;
    case "reciprocal":
      math = `${p.a} \xF7 (${p.b}) = ${p.a} \xD7 (${p.inverse}) = ${p.result}`;
      break;
    case "divisionScale":
      math = `(${p.a} \xD7 ${p.factor}) \xF7 (${p.b} \xD7 ${p.factor}) = ${p.left} \xF7 ${p.right} = ${p.result}`;
      break;
    case "rootBring":
      math = `${p.pair} \u2192 ${p.total}`;
      break;
    case "rootTrial":
      math = `(${p.base} + ${p.digit}) \xD7 ${p.digit} = ${p.used} \u2264 ${p.total}`;
      break;
    case "rootDigit":
      math = `${p.partial}; R = ${p.remain}`;
      break;
    case "roundRoot":
      math = `\u2248 ${p.result} (${p.places} d.p.; ${p.guard})`;
      break;
    case "commonParts":
      math = `${p.left} ${p.op} ${p.right}`;
      break;
    case "combineParts":
      math = `(${p.left} ${p.op} ${p.right}) / ${p.den} = ${p.result}`;
      break;
    case "lowerOn":
    case "lowerOff":
    case "upperOn":
    case "upperOff":
      if (/^\d+$/.test(String(p.amount)) && /^\d+$/.test(String(p.place)) && !s.before.value.startsWith("-")) {
        const value = BigInt(p.amount) * BigInt(p.place);
        const sign = s.kind.endsWith("On") ? "" : "\u2212";
        math = `${sign}${p.amount} \xD7 ${p.place} = ${sign}${value}`;
      } else {
        math = `${s.kind.endsWith("On") ? "+" : "\u2212"}${p.amount} \xD7 ${p.place} \xB7 ${p.from} \u2192 ${p.to}`;
      }
      break;
    case "makeTen":
      math = `+${p.digit} = \u2212${p.complement} +10`;
      break;
    case "borrowTen":
      math = `\u2212${p.digit} = \u221210 +${p.complement}`;
      break;
    case "operation":
      math = `${p.a} ${p.op} ${p.b}`;
      break;
    case "partialProduct":
      math = `${p.a} \xD7 ${p.factor} = ${p.part}`;
      break;
    case "divideDigit":
      math = `${p.total} \xF7 ${p.divisor} \u2192 ${p.digit}; ${p.total} \u2212 ${p.used} = ${p.remain}`;
      break;
    case "divideCheck":
      math = `${p.result} \xD7 ${p.b} = ${p.a}`;
      break;
    case "rootCheck":
      math = `${p.result} \xD7 ${p.result} = ${p.a}`;
      break;
    case "power":
      math = Array(Math.max(0, Number(p.b))).fill(p.a).join(" \xD7 ") + ` = ${p.result}`;
      if (Number(p.b) < 0) math = `${p.a} ^ (${p.b}) = ${p.result}`;
      break;
    case "collect":
      math = `(${p.coefficient}) \xD7 x = ${p.constant}`;
      break;
    case "solveX":
      math = `x = ${p.constant} \xF7 (${p.coefficient}) = ${p.result}`;
      break;
    case "verifyX":
      math = `x = ${p.result}; ${p.left} = ${p.right}`;
      break;
    case "balance":
      math = `(${p.leftA})x + (${p.leftB}) = (${p.rightA})x + (${p.rightB})`;
      break;
    default:
      math = p.result || p.value || s.after.value;
  }
  return { text, math };
}
