export function sanitizePrefs(p = {}) {
  const r = { ...defaults };
  for (const [k, values] of Object.entries({
    journey: ["normal", "mastery"],
    density: ["auto", "compact", "chunky"],
    theme: ["system", "light", "dark"],
    surface: ["classic", "wood", "cyber", "orchid"],
    fingerStyle: ["individual", "abacus"],
    fingerPose: ["foldedCounts", "extendedCounts"],
    renderer: ["3d", "2d"]
  }))
    if (values.includes(p[k])) r[k] = p[k];
  for (const k of ["motion", "lowPower", "guide", "setupSeen", "fingerSeen", "autoRead", "sfx"])
    if (typeof p[k] === "boolean") r[k] = p[k];
  if ([500, 1e3, 2e3, 3e3].includes(Number(p.duration)))
    r.duration = Number(p.duration);
  for (const k of ["integerColumns", "decimalColumns"])
    if (Number.isInteger(Number(p[k])) && Number(p[k]) >= 0 && Number(p[k]) <= (k === "integerColumns" ? 18 : 8))
      r[k] = Number(p[k]);
  if (/^#[0-9a-f]{6}$/i.test(p.customColor || ""))
    r.customColor = p.customColor;
  return r;
}
export function readPrefs() {
  try {
    const saved = JSON.parse(localStorage.getItem("academy-studio") || "{}");
    if ((saved.version || 0) < 5 && Number(saved.duration) < 2e3)
      saved.duration = 2e3;
    const prefs2 = sanitizePrefs(saved);
    localStorage.setItem("academy-studio", JSON.stringify(prefs2));
    return prefs2;
  } catch {
    return { ...defaults };
  }
}
export function writePrefs(p) {
  try {
    localStorage.setItem("academy-studio", JSON.stringify(sanitizePrefs(p)));
  } catch {
  }
}
export function applyPrefs(p) {
  const root = document.documentElement;
  root.dataset.density = p.density === "auto" ? (globalThis.innerWidth || 1e3) < 420 ? "compact" : "chunky" : p.density;
  root.dataset.theme = p.theme === "system" ? globalThis.matchMedia?.("(prefers-color-scheme: dark)").matches ? "dark" : "light" : p.theme;
  root.dataset.surface = p.surface;
  root.style.setProperty("--custom-bead", p.customColor);
  root.style.setProperty("--move-duration", `${p.duration}ms`);
}
export function canonicalMask(d) {
  return (d >= 5 ? 1 : 0) | (1 << d % 5) - 1 << 1;
}
export function maskValue(mask) {
  let value = mask & 1 ? 5 : 0;
  for (let i = 1; i <= 4; i++) value += mask >> i & 1;
  return value;
}
export function tapFinger(mask, index, style = "individual") {
  if (index === 0 || style === "individual") return mask ^ 1 << index;
  const prefix = (1 << index) - 1 << 1;
  return mask & 1 << index ? mask & ~prefix : mask | prefix;
}
export function st(key, lang2 = "en") {
  return rows3[key]?.[Math.max(0, langs.indexOf(lang2))] || key;
}
export function motionAllowed(p) {
  return p.motion && !globalThis.matchMedia?.("(prefers-reduced-motion: reduce)").matches;
}

